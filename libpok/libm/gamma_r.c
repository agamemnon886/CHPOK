/**
 * @file
 * gamma_r() of libpok's math library (fdlibm, from Sun Microsystems).
 */
#include <config.h>
#ifdef POK_NEEDS_LIBMATH

/*
 * wrapper double gamma_r(double x, int *signgamp)
 */

#include <libm.h>
#include "math_private.h"

/**
 * @funcname `gamma_r`
 *
 * @description
 * Computes the logarithm of the absolute value of the gamma function of x (as
 * lgamma()); the sign of gamma(x) is stored in *signgamp (reentrant).
 *
 * @params
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `x` | `double` | [in] The argument. |
 * | `signgamp` | `int *` | [out] Where the sign of gamma(x) is stored. |
 *
 * @return The result.
 *
 * @globals
 * None.
 *
 * @locals
 * None.
 *
 * @hlr
 *
 * @llr
 *
 * @design
 * 1. Call `__ieee754_lgamma_r()` with the arguments `x` and `signgamp`, and
 *    return its result.
 *
 * @calls
 * - `__ieee754_lgamma_r()`
 */
double
gamma_r(double x, int *signgamp) /* wrapper lgamma_r */
{
#ifdef _IEEE_LIBM
	return __ieee754_lgamma_r(x,signgamp);
#else
        double y;
        y = __ieee754_lgamma_r(x,signgamp);
        if(_LIB_VERSION == _IEEE_) return y;
        if(!finite(y)&&finite(x)) {
            if(floor(x)==x&&x<=0.0)
                return __kernel_standard(x,x,41); /* gamma pole */
            else
                return __kernel_standard(x,x,40); /* gamma overflow */
        } else
            return y;
#endif
}

#endif
