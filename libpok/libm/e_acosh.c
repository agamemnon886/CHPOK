/**
 * @file
 * `__ieee754_acosh()` of libpok's math library (fdlibm, from Sun Microsystems).
 */
/* __ieee754_acosh(x)
 * Method :
 *	Based on
 *		acosh(x) = log [ x + sqrt(x*x-1) ]
 *	we have
 *		acosh(x) := log(x)+ln2,	if x is large; else
 *		acosh(x) := log(2x-1/(sqrt(x*x-1)+x)) if x>2; else
 *		acosh(x) := log1p(t+sqrt(2.0*t+t*t)); where t=x-1.
 *
 * Special cases:
 *	acosh(x) is NaN with signal if x<1.
 *	acosh(NaN) is NaN without signal.
 */

#include <config.h>
#ifdef POK_NEEDS_LIBMATH

#include <libm.h>
#include "math_private.h"

static const double
one	= 1.0,
ln2	= 6.93147180559945286227e-01;  /* 0x3FE62E42, 0xFEFA39EF */

/**
 * @funcname `__ieee754_acosh`
 *
 * @description
 * Computes the inverse hyperbolic cosine of x: the IEEE 754 core of acosh().
 *
 * @params
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `x` | `double` | [in] The argument. |
 *
 * @return The result.
 *
 * @globals
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `ln2` | `const double` | A constant of the algorithm |
 * | `one` | `const double` | A constant of the algorithm |
 *
 * @locals
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `hx` | `int32_t` | The high word of x |
 * | `lx` | `uint32_t` | The low word of x |
 * | `t` | `double` | A temporary of the computation |
 *
 * @hlr
 *
 * @llr
 *
 * @design
 * 1. Use the macro `EXTRACT_WORDS()` with the arguments `hx`, `lx` and `x`.
 * 2. If `hx` is less than `0x3ff00000`:
 *    1. Return `(x-x)/(x-x)`.
 * 3. Otherwise, if `hx` is greater than or equal to `0x41b00000`:
 *    1. If `hx` is greater than or equal to `0x7ff00000`:
 *       1. Return `x+x`.
 *    2. Otherwise:
 *       1. Return `__ieee754_log(x)+ln2`.
 * 4. Otherwise, if `((hx-0x3ff00000)|lx)` is equal to `0`:
 *    1. Return `0.0`.
 * 5. Otherwise, if `hx` is greater than `0x40000000`:
 *    1. Set `t` to `x*x`.
 *    2. Call `__ieee754_log()` with the argument
 *       `2.0*x-one/(x+__ieee754_sqrt(t-one))`, and return its result.
 * 6. Otherwise:
 *    1. Set `t` to `x-one`.
 *    2. Call `log1p()` with the argument `t+sqrt(2.0*t+t*t)`, and return its
 *       result.
 *
 * @calls
 * - `__ieee754_log()`
 * - `__ieee754_sqrt()`
 * - `log1p()`
 * - `sqrt()`
 */
double
__ieee754_acosh(double x)
{
	double t;
	int32_t hx;
	uint32_t lx;
	EXTRACT_WORDS(hx,lx,x);
	if(hx<0x3ff00000) {		/* x < 1 */
	    return (x-x)/(x-x);
	} else if(hx >=0x41b00000) {	/* x > 2**28 */
	    if(hx >=0x7ff00000) {	/* x is inf of NaN */
	        return x+x;
	    } else
		return __ieee754_log(x)+ln2;	/* acosh(huge)=log(2x) */
	} else if(((hx-0x3ff00000)|lx)==0) {
	    return 0.0;			/* acosh(1) = 0 */
	} else if (hx > 0x40000000) {	/* 2**28 > x > 2 */
	    t=x*x;
	    return __ieee754_log(2.0*x-one/(x+__ieee754_sqrt(t-one)));
	} else {			/* 1<x<2 */
	    t = x-one;
	    return log1p(t+sqrt(2.0*t+t*t));
	}
}

#endif
