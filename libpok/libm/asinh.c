/**
 * @file
 * asinh() of libpok's math library (fdlibm, from Sun Microsystems).
 */
/* asinh(x)
 * Method :
 *	Based on
 *		asinh(x) = sign(x) * log [ |x| + sqrt(x*x+1) ]
 *	we have
 *	asinh(x) := x  if  1+x*x=1,
 *		 := sign(x)*(log(x)+ln2)) for large |x|, else
 *		 := sign(x)*log(2|x|+1/(|x|+sqrt(x*x+1))) if|x|>2, else
 *		 := sign(x)*log1p(|x| + x^2/(1 + sqrt(1+x^2)))
 */

#include <config.h>
#ifdef POK_NEEDS_LIBMATH

#include <types.h>
#include <libm.h>
#include "math_private.h"

static const double
one =  1.00000000000000000000e+00, /* 0x3FF00000, 0x00000000 */
ln2 =  6.93147180559945286227e-01, /* 0x3FE62E42, 0xFEFA39EF */
huge=  1.00000000000000000000e+300;

/**
 * @funcname `asinh`
 *
 * @description
 * Computes the inverse hyperbolic sine of x (C standard).
 *
 * @params
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `x` | `double` | [in] The argument. |
 *
 * @return The result.
 *
 * @globals
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `huge` | `const double` | A constant of the algorithm |
 * | `ln2` | `const double` | A constant of the algorithm |
 * | `one` | `const double` | A constant of the algorithm |
 *
 * @locals
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `hx` | `int32_t` | The high word of x |
 * | `ix` | `int32_t` | The high word of x without the sign bit |
 * | `t` | `double` | A temporary of the computation |
 * | `w` | `double` | A temporary of the computation |
 *
 * @hlr
 *
 * @llr
 *
 * @design
 * 1. Use the macro `GET_HIGH_WORD()` with the arguments `hx` and `x`.
 * 2. Set `ix` to `hx&0x7fffffff`.
 * 3. If `ix` is greater than or equal to `0x7ff00000`:
 *    1. Return `x+x`.
 * 4. If `ix` is less than `0x3e300000`:
 *    1. If `huge+x` is greater than `one`:
 *       1. Return `x`.
 * 5. If `ix` is greater than `0x41b00000`:
 *    1. Set `w` to `__ieee754_log(fabs(x))+ln2`.
 * 6. Otherwise, if `ix` is greater than `0x40000000`:
 *    1. Call `fabs()` with the argument `x`, and store the result in `t`.
 *    2. Call `__ieee754_log()` with the argument
 *       `2.0*t+one/(__ieee754_sqrt(x*x+one)+t)`, and store the result in `w`.
 * 7. Otherwise:
 *    1. Set `t` to `x*x`.
 *    2. Call `log1p()` with the argument
 *       `fabs(x)+t/(one+__ieee754_sqrt(one+t))`, and store the result in `w`.
 * 8. If `hx` is greater than `0`:
 *    1. Return `w`.
 * 9. Otherwise:
 *    1. Return `-w`.
 *
 * @calls
 * - `__ieee754_log()`
 * - `fabs()`
 * - `__ieee754_sqrt()`
 * - `log1p()`
 */
double
asinh(double x)
{
	double t,w;
	int32_t hx,ix;
	GET_HIGH_WORD(hx,x);
	ix = hx&0x7fffffff;
	if(ix>=0x7ff00000) return x+x;	/* x is inf or NaN */
	if(ix< 0x3e300000) {	/* |x|<2**-28 */
	    if(huge+x>one) return x;	/* return x inexact except 0 */
	}
	if(ix>0x41b00000) {	/* |x| > 2**28 */
	    w = __ieee754_log(fabs(x))+ln2;
	} else if (ix>0x40000000) {	/* 2**28 > |x| > 2.0 */
	    t = fabs(x);
	    w = __ieee754_log(2.0*t+one/(__ieee754_sqrt(x*x+one)+t));
	} else {		/* 2.0 > |x| > 2**-28 */
	    t = x*x;
	    w =log1p(fabs(x)+t/(one+__ieee754_sqrt(one+t)));
	}
	if(hx>0) return w; else return -w;
}

#endif

