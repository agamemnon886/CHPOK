/**
 * @file
 * `__ieee754_acoshf()` of libpok's math library (fdlibm, from Sun
 * Microsystems).
 */
#include <config.h>
#ifdef POK_NEEDS_LIBMATH

#include <libm.h>
#include "math_private.h"

static const float
one	= 1.0,
ln2	= 6.9314718246e-01;  /* 0x3f317218 */

/**
 * @funcname `__ieee754_acoshf`
 *
 * @description
 * Computes the inverse hyperbolic cosine of x, in float: the IEEE 754 core of
 * acoshf().
 *
 * @params
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `x` | `float` | [in] The argument. |
 *
 * @return The result.
 *
 * @globals
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `ln2` | `const float` | A constant of the algorithm |
 * | `one` | `const float` | A constant of the algorithm |
 *
 * @locals
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `hx` | `int32_t` | The bits of x |
 * | `t` | `float` | A temporary of the computation |
 *
 * @hlr
 *
 * @llr
 *
 * @design
 * 1. Use the macro `GET_FLOAT_WORD()` with the arguments `hx` and `x`.
 * 2. If `hx` is less than `0x3f800000`:
 *    1. Return `(x-x)/(x-x)`.
 * 3. Otherwise, if `hx` is greater than or equal to `0x4d800000`:
 *    1. If `hx` is greater than or equal to `0x7f800000`:
 *       1. Return `x+x`.
 *    2. Otherwise:
 *       1. Return `__ieee754_logf(x)+ln2`.
 * 4. Otherwise, if `hx` is equal to `0x3f800000`:
 *    1. Return `0.0`.
 * 5. Otherwise, if `hx` is greater than `0x40000000`:
 *    1. Set `t` to `x*x`.
 *    2. Call `__ieee754_logf()` with the argument
 *       `(float)2.0*x-one/(x+__ieee754_sqrtf(t-one))`, and return its result.
 * 6. Otherwise:
 *    1. Set `t` to `x-one`.
 *    2. Call `log1pf()` with the argument `t+sqrtf((float)2.0*t+t*t)`, and
 *       return its result.
 *
 * @calls
 * - `__ieee754_logf()`
 * - `__ieee754_sqrtf()`
 * - `log1pf()`
 * - `sqrtf()`
 */
float
__ieee754_acoshf(float x)
{
	float t;
	int32_t hx;
	GET_FLOAT_WORD(hx,x);
	if(hx<0x3f800000) {		/* x < 1 */
	    return (x-x)/(x-x);
	} else if(hx >=0x4d800000) {	/* x > 2**28 */
	    if(hx >=0x7f800000) {	/* x is inf of NaN */
	        return x+x;
	    } else
		return __ieee754_logf(x)+ln2;	/* acosh(huge)=log(2x) */
	} else if (hx==0x3f800000) {
	    return 0.0;			/* acosh(1) = 0 */
	} else if (hx > 0x40000000) {	/* 2**28 > x > 2 */
	    t=x*x;
	    return __ieee754_logf((float)2.0*x-one/(x+__ieee754_sqrtf(t-one)));
	} else {			/* 1<x<2 */
	    t = x-one;
	    return log1pf(t+sqrtf((float)2.0*t+t*t));
	}
}

#endif

