/**
 * @file
 * copysignf() of libpok's math library (fdlibm, from Sun Microsystems).
 */
/*
 * copysignf(float x, float y)
 * copysignf(x,y) returns a value with the magnitude of x and
 * with the sign bit of y.
 */

#include <config.h>
#ifdef POK_NEEDS_LIBMATH
#include "math_private.h"

/**
 * @funcname `copysignf`
 *
 * @description
 * Computes x with the sign of y, in float (C standard).
 *
 * @params
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `x` | `float` | [in] The argument. |
 * | `y` | `float` | [in] The second argument. |
 *
 * @return The result.
 *
 * @globals
 * None.
 *
 * @locals
 * | Name | Type | Description |
 * |------|------|-------------|
 * | `ix` | `uint32_t` | The bits of x |
 * | `iy` | `uint32_t` | The bits of y |
 *
 * @hlr
 *
 * @llr
 *
 * @design
 * 1. Use the macro `GET_FLOAT_WORD()` with the arguments `ix` and `x`.
 * 2. Use the macro `GET_FLOAT_WORD()` with the arguments `iy` and `y`.
 * 3. Use the macro `SET_FLOAT_WORD()` with the arguments `x` and
 *    `(ix&0x7fffffff)|(iy&0x80000000)`.
 * 4. Return `x`.
 *
 * @calls
 * None.
 */
float
copysignf(float x, float y)
{
	uint32_t ix,iy;
	GET_FLOAT_WORD(ix,x);
	GET_FLOAT_WORD(iy,y);
	SET_FLOAT_WORD(x,(ix&0x7fffffff)|(iy&0x80000000));
        return x;
}

#endif
